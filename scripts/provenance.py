"""Results registry: one row per finished run, linked to the sweep file + line that produced it.

    python scripts/provenance.py                      # scans results*/ -> results/REGISTRY.csv + results/REGISTRY.md
    python scripts/provenance.py --roots results results_smoke

Provenance comes from results/<run>/config.json["provenance"] (git commit, sweep, line, SLURM job; recorded
since commit "provenance"). For older runs the sweep file and line are reconstructed by recomputing the run
name of every line in slurm/sweeps/*.txt and matching it; git commit is then unknown.
"""
import argparse
import csv
import glob
import json
import os
import shlex
import sys
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

FLAGS = ["n_estimators", "pca", "res", "up", "sampling", "max_ctx", "img_size", "letterbox", "score_norm",
         "debias", "whiten", "support_flip", "anchors", "refine", "logreg_C", "knn_k"]
DEFAULTS = {"pca": 0, "res": "patch", "up": "bilinear", "sampling": "all", "max_ctx": 10000, "img_size": 512,
            "letterbox": 0, "score_norm": "none", "debias": 0, "whiten": 0.0, "support_flip": 0,
            "anchors": "none", "refine": "none", "logreg_C": 1.0, "knn_k": 16}


def sweep_index():
    """run name -> list of (sweep file, line number) for every line of every sweep file."""
    try:
        from tabpfnseg.run import get_args, run_name
    except Exception as e:  # torch etc. missing: no reconstruction, recorded provenance still works
        print(f"[provenance] cannot import tabpfnseg.run ({e}); skipping sweep-line reconstruction")
        return {}
    index = defaultdict(list)
    for f in sorted(glob.glob(os.path.join(REPO, "slurm", "sweeps", "*.txt"))):
        for i, line in enumerate(open(f), 1):
            if line.strip():
                try:
                    index[run_name(get_args(shlex.split(line)))].append((os.path.relpath(f, REPO), i))
                except SystemExit:
                    pass
    return index


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--roots", nargs="+", default=sorted(glob.glob(os.path.join(REPO, "results*"))))
    ap.add_argument("--out", default=os.path.join(REPO, "results", "REGISTRY"))
    a = ap.parse_args()
    index = sweep_index()
    rows = []
    for root in a.roots:
        for f in sorted(glob.glob(os.path.join(root, "*", "summary.json"))):
            d = os.path.dirname(f)
            run = os.path.basename(d)
            s = json.load(open(f))
            cfg_f = os.path.join(d, "config.json")
            cfg = json.load(open(cfg_f)) if os.path.exists(cfg_f) else {}
            prov = cfg.get("provenance", {})
            if prov.get("sweep"):
                sweeps = f"{os.path.relpath(prov['sweep'], REPO) if os.path.isabs(prov['sweep']) else prov['sweep']}:{prov.get('sweep_line', '?')}"
                source = "recorded"
            elif run in index:
                sweeps = " ".join(f"{p}:{n}" for p, n in index[run])
                source = "reconstructed"
            else:
                sweeps, source = "", "unknown"
            flags = " ".join(f"{k}={cfg[k]}" for k in FLAGS
                             if k in cfg and cfg[k] != DEFAULTS.get(k) and not (k == "n_estimators" and
                                                                                 not str(cfg.get("method", "")).startswith("tabpfn")))
            rows.append({
                "root": os.path.basename(root), "run": run,
                "dataset": cfg.get("dataset", ""), "split": cfg.get("split", ""), "shots": cfg.get("shots", ""),
                "seed": cfg.get("seed", ""), "method": cfg.get("method", ""), "backbone": cfg.get("backbone", ""),
                "features": cfg.get("features", ""), "flags": flags,
                "n_episodes": s.get("n_episodes", ""), "mIoU": round(s.get("mIoU", float("nan")), 2),
                "FB-IoU": round(s.get("FB-IoU", float("nan")), 2),
                "s_per_ep": round(s.get("seconds_per_episode", float("nan")), 2),
                "git_commit": prov.get("git_commit", "")[:8], "git_dirty": prov.get("git_dirty", ""),
                "slurm_job": prov.get("slurm_job", ""), "sweep": sweeps, "provenance": source,
            })
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out + ".csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]) if rows else ["run"])
        w.writeheader()
        w.writerows(rows)
    # markdown, grouped by dataset / split / shots
    groups = defaultdict(list)
    for r in rows:
        groups[(r["root"], r["dataset"], r["split"], r["shots"])].append(r)
    with open(a.out + ".md", "w") as fh:
        fh.write("# Results registry (generated by scripts/provenance.py — do not edit)\n\n")
        for key in sorted(groups, key=str):
            fh.write(f"## {key[0]} · {key[1]} {key[2]} · {key[3]}-shot\n\n")
            fh.write("| method | features | flags | n | mIoU | FB-IoU | s/ep | sweep:line | commit |\n")
            fh.write("|---|---|---|---|---|---|---|---|---|\n")
            for r in sorted(groups[key], key=lambda r: -r["mIoU"] if r["mIoU"] == r["mIoU"] else 0):
                fh.write(f"| {r['method']} | `{r['features']}` | {r['flags']} | {r['n_episodes']} | **{r['mIoU']}** | "
                         f"{r['FB-IoU']} | {r['s_per_ep']} | {r['sweep']} | {r['git_commit'] or '–'} |\n")
            fh.write("\n")
    n_rec = sum(r["provenance"] == "recorded" for r in rows)
    n_rec2 = sum(r["provenance"] == "reconstructed" for r in rows)
    print(f"{len(rows)} runs -> {a.out}.csv / .md  (provenance: {n_rec} recorded, {n_rec2} reconstructed, "
          f"{len(rows) - n_rec - n_rec2} unknown)")


if __name__ == "__main__":
    main()
